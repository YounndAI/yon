/**
 * Structured Output Comparison Suite
 *
 * Pillar: Cognitive Economy
 * Category: local (simulated — no LLM calls, uses pre-built payloads)
 * Validates: YON vs JSON structured output characteristics.
 *
 * Tests:
 * 1. output-byte-comparison — Byte size of equivalent data in YON vs JSON
 * 2. output-escape-burden — Number of escapes required in JSON vs YON
 * 3. output-readability-ratio — Lines vs bracket depth
 */

import { startTimer, localTimestamp } from '@younndai/ai-relay';
import type { BenchmarkResult, TestResult } from '../core/types.js';

// ---------------------------------------------------------------------------
// Simulated structured outputs (as would be generated by an LLM)
// ---------------------------------------------------------------------------

const SAMPLE_YON = `@DOC ver=2.0 | id=code-review | title="Code Review" | kind=report
@SEC name="Summary"
@NOTE text="The function handleAuth() has three issues."
@MAP id=issue-1 | severity:str="high" | line:int=42 | message:str="Missing null check on user.session"
@MAP id=issue-2 | severity:str="medium" | line:int=87 | message:str="Unused import: \`lodash\`"
@MAP id=issue-3 | severity:str="low" | line:int=103 | message:str="console.log should use logger"
@SEC name="Code Snippet"
@BEGIN lang=typescript
function handleAuth(user: User) {
  // This line has a "quoted string" and special chars: <>&
  if (user.session?.valid) {
    return user.session.token;
  }
  throw new Error("Session invalid");
}
@END
@SEC name="Recommendation"
@NOTE text="Add null guard at line 42. Remove unused import. Replace console.log with structured logger."`;

const SAMPLE_JSON = JSON.stringify({
  id: 'code-review',
  title: 'Code Review',
  kind: 'report',
  sections: [
    {
      name: 'Summary',
      notes: ['The function handleAuth() has three issues.'],
    },
    {
      name: 'Issues',
      items: [
        { id: 'issue-1', severity: 'high', line: 42, message: 'Missing null check on user.session' },
        { id: 'issue-2', severity: 'medium', line: 87, message: 'Unused import: `lodash`' },
        { id: 'issue-3', severity: 'low', line: 103, message: 'console.log should use logger' },
      ],
    },
    {
      name: 'Code Snippet',
      lang: 'typescript',
      code: 'function handleAuth(user: User) {\n  // This line has a "quoted string" and special chars: <>&\n  if (user.session?.valid) {\n    return user.session.token;\n  }\n  throw new Error("Session invalid");\n}',
    },
    {
      name: 'Recommendation',
      notes: ['Add null guard at line 42. Remove unused import. Replace console.log with structured logger.'],
    },
  ],
}, null, 2);

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

function testByteComparison(): TestResult {
  const yonBytes = new TextEncoder().encode(SAMPLE_YON).length;
  const jsonBytes = new TextEncoder().encode(SAMPLE_JSON).length;
  const ratio = Math.round((yonBytes / jsonBytes) * 100);

  return {
    id: 'output-byte-comparison',
    name: 'Structured Output — Byte Size Comparison',
    passed: true, // Informational
    metric: {
      name: 'yon_vs_json_bytes',
      value: ratio,
      unit: '%',
      comparison: {
        baseline: 100,
        baselineLabel: 'JSON size',
        delta: `${ratio - 100}%`,
      },
    },
    secondaryMetrics: [
      { name: 'yon_bytes', value: yonBytes, unit: 'bytes' },
      { name: 'json_bytes', value: jsonBytes, unit: 'bytes' },
    ],
    outcome: ratio < 100 ? 'advantage' : ratio > 100 ? 'disadvantage' : 'tied',
    detail:
      `Equivalent structured output: YON ${yonBytes} bytes vs JSON ${jsonBytes} bytes (${ratio}%). ` +
      `YON includes embedded code without escaping; JSON requires escape sequences.`,
  };
}

function testEscapeBurden(): TestResult {
  // Count escape sequences in JSON output
  const jsonEscapes = (SAMPLE_JSON.match(/\\["\\/bfnrt]/g) || []).length;
  const yonEscapes = 0; // YON uses @BEGIN/@END, no escaping

  return {
    id: 'output-escape-burden',
    name: 'Structured Output — Escape Burden',
    passed: yonEscapes < jsonEscapes,
    metric: {
      name: 'escape_delta',
      value: jsonEscapes - yonEscapes,
      unit: 'escapes',
      comparison: {
        baseline: jsonEscapes,
        baselineLabel: 'JSON escapes',
        delta: `−${jsonEscapes}`,
      },
    },
    secondaryMetrics: [
      { name: 'yon_escapes', value: yonEscapes, unit: 'escapes' },
      { name: 'json_escapes', value: jsonEscapes, unit: 'escapes' },
    ],
    outcome: 'advantage',
    detail:
      `JSON required ${jsonEscapes} escape sequences for embedded code and quotes. ` +
      `YON required ${yonEscapes} — @BEGIN/@END blocks embed foreign content without transformation.`,
  };
}

function testReadabilityRatio(): TestResult {
  const yonLines = SAMPLE_YON.split('\n').length;
  const jsonLines = SAMPLE_JSON.split('\n').length;

  // Measure max nesting depth in JSON
  let maxDepth = 0;
  let depth = 0;
  for (const ch of SAMPLE_JSON) {
    if (ch === '{' || ch === '[') depth++;
    if (ch === '}' || ch === ']') depth--;
    if (depth > maxDepth) maxDepth = depth;
  }

  // YON has flat nesting (max 1 level — section context)
  const yonMaxDepth = 1;

  return {
    id: 'output-readability-ratio',
    name: 'Structured Output — Readability (Lines vs Depth)',
    passed: yonMaxDepth < maxDepth,
    metric: {
      name: 'nesting_depth_delta',
      value: maxDepth - yonMaxDepth,
      unit: 'levels',
    },
    secondaryMetrics: [
      { name: 'yon_lines', value: yonLines, unit: 'lines' },
      { name: 'json_lines', value: jsonLines, unit: 'lines' },
      { name: 'yon_max_depth', value: yonMaxDepth, unit: 'levels' },
      { name: 'json_max_depth', value: maxDepth, unit: 'levels' },
    ],
    outcome: 'advantage',
    detail:
      `YON: ${yonLines} lines, max depth ${yonMaxDepth}. ` +
      `JSON: ${jsonLines} lines, max depth ${maxDepth}. ` +
      `Flat structure is easier to scan, grep, and stream.`,
  };
}

// ---------------------------------------------------------------------------
// Suite
// ---------------------------------------------------------------------------

export async function runStructuredOutputComparison(): Promise<BenchmarkResult> {
  const elapsed = startTimer();

  const tests: TestResult[] = [
    testByteComparison(),
    testEscapeBurden(),
    testReadabilityRatio(),
  ];

  const durationMs = elapsed();
  const passed = tests.filter((t) => t.passed).length;

  return {
    suiteId: 'structured-output-comparison',
    suiteName: 'Structured Output Comparison',
    pillar: 'cognitive-economy',
    tests,
    summary: {
      total: tests.length,
      passed,
      failed: tests.length - passed,
      durationMs,
    },
    timestamp: localTimestamp(),
  };
}
